import type { MergeBlock, MergeDecision, MergeFileEntry, MergeFileKind } from "./merge.types";

/** Paths never compared: gitignore-like, a leading "/" anchors to the server root. */
export const DEFAULT_EXCLUSIONS = [
  "/mods/",
  "/libraries/",
  "*.jar",
  "/logs/",
  "/crash-reports/",
  "/backups/",
  ".cache/",
  "*.tmp",
  // Found on a real installation: archives kept at the root, logs and files regenerated at startup.
  "/*.zip",
  "*.log",
  "/coretweaks/cache/",
  "/coretweaks/out/",
  "/GregTech.lang",
] as const;

export const KIND_LABELS: Record<MergeFileKind, string> = {
  "user-modified": "Changed by you",
  conflict: "Changed on both sides",
  "user-added": "Added by you",
  "mod-added": "Created by mods",
  "removed-by-new": "Removed by new version",
  regenerated: "Regenerated by mods",
};

/**
 * Files created outside the world are recreated by mods at the next start, except under these
 * folders, which hold data worth carrying over (ServerUtilities ranks and players, JourneyMap).
 */
export const CARRIED_OVER_ADDITIONS = ["serverutilities/", "journeymap/"] as const;

export function isCarriedOverAddition(path: string): boolean {
  return CARRIED_OVER_ADDITIONS.some((folder) => path.startsWith(folder));
}

/** Mod rewrites and files mods recreate are kept out of the main list: they are not user changes. */
export function isUserChange(file: MergeFileEntry): boolean {
  return file.kind !== "regenerated" && file.kind !== "mod-added";
}

/** Your edits and the additions worth keeping are ticked; conflicts stay undecided. */
export function defaultDecisions(files: MergeFileEntry[]): Map<string, MergeDecision> {
  const decisions = new Map<string, MergeDecision>();
  for (const file of files) {
    if (file.kind === "user-modified" || file.kind === "user-added") {
      decisions.set(file.path, { path: file.path, action: "take-old" });
    } else if (file.kind !== "conflict") {
      decisions.set(file.path, { path: file.path, action: "keep-new" });
    }
  }
  return decisions;
}

/** Git-style markers: the reviewer resolves them in the editor, like a merge conflict. */
export const CONFLICT_START = "<<<<<<< your version";
export const CONFLICT_SEPARATOR = "=======";
export const CONFLICT_END = ">>>>>>> new version";

/** Pre-merged text: one-sided changes are applied, conflicting ones are left marked. */
export function buildMergedText(blocks: MergeBlock[]): string {
  const lines = blocks.flatMap((block) => block.type === "conflict"
    ? [CONFLICT_START, ...block.old, CONFLICT_SEPARATOR, ...block.new, CONFLICT_END]
    : block.lines);
  return lines.join("\n");
}

export function hasConflictMarkers(text: string): boolean {
  return text.split("\n").some((line) => line === CONFLICT_START || line === CONFLICT_SEPARATOR || line === CONFLICT_END);
}

export function groupByDirectory(files: MergeFileEntry[]): Array<{ directory: string; files: MergeFileEntry[] }> {
  const groups = new Map<string, MergeFileEntry[]>();
  for (const file of files) {
    const separator = file.path.lastIndexOf("/");
    const directory = separator < 0 ? "/" : file.path.slice(0, separator);
    groups.set(directory, [...(groups.get(directory) ?? []), file]);
  }
  return [...groups].map(([directory, entries]) => ({ directory, files: entries }));
}
